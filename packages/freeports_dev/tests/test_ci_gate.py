"""The gate: which commits go through, which are refused, and which are only reported.

`freeports-dev ci-check` is the one place in this workspace that stops a commit. It measures
nothing itself — it reads what the measurement commands left in `reports/`, the minima in
`ci.yaml`, and the class of the branch. That separation is what makes a threshold survivable: when
a commit is refused, the number that refused it is in a file, written by a command the person can
re-run by hand.

Every cell of the matrix below is a test here, **including the ones that must not refuse** — those
are the ones a change would silently break, because nobody notices a gate that stopped being strict
until the day it should have stopped something.

    verdict          dev       prod
    pass             —         —
    below            notify    refuse
    unmeasured       notify    refuse
    stale            notify    refuse
    no threshold     listed    listed

The two that are easy to get wrong:

**`unmeasured` is never a pass.** A figure nobody could compute is not a figure above the
threshold. Reporting it as one is exactly the failure this project already ruled out for a
methodology page it could not reach — unverifiable is not granted, and neither is unmeasured.

**`stale` is what makes the fast/slow split honest.** The hook measures the fast metrics at every
commit and reads the slow ones from the last `make ci`. Without staleness, a figure from three
weeks ago would gate today's commit and the split would quietly become a way of never measuring
the slow half at all.

One rule is *not* here and its absence is deliberate: grant integrity never refuses, on any branch.
A granted reference output regenerated by `make-tests` is ordinary work, and a contributor who does
not hold the granting key could not clear such a gate at all.
"""

