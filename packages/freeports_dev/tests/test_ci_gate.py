class TestAFigureTakenAtAnotherCommit:
    """What makes the fast/slow split honest rather than a way of never measuring the slow half."""

    def test_a_measurement_from_another_commit_is_stale(self, engine):
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 91.2, head="old")},
            head="new",
        )
        assert verdict_for(gate, "tests.rust.lines").state == ci_gate.STALE

    def test_even_when_it_clears_the_minimum_easily(self, engine):
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 99.9, head="old")},
            head="new",
        )
        assert verdict_for(gate, "tests.rust.lines").state != ci_gate.PASS

    def test_the_message_names_the_command_that_fixes_it(self, engine):
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 91.2, head="oldcommit")},
            head="newcommit",
        )
        assert "make ci" in verdict_for(gate, "tests.rust.lines").reason

    def test_one_taken_at_this_commit_is_current(self, engine):
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 91.2, head="same")},
            head="same",
        )
        assert verdict_for(gate, "tests.rust.lines").state == ci_gate.PASS

    def test_a_repository_with_no_commit_cannot_have_a_stale_figure(self, engine):
        """Guessing here would refuse commits in a repository nobody has ever committed to."""
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 91.2, head="anything")},
            head=None,
        )
        assert verdict_for(gate, "tests.rust.lines").state == ci_gate.PASS

    def test_a_measurement_recording_no_commit_is_judged_on_its_value(self, engine):
        gate = judge(
            engine,
            "thresholds:\n  tests.rust.lines: 50\n",
            {"tests.rust.lines": measured("tests.rust.lines", 91.2, head=None)},
            head="new",
        )
        assert verdict_for(gate, "tests.rust.lines").state == ci_gate.PASS

    def test_it_is_reported_on_dev_and_refuses_on_prod(self, engine):
        stale = {"tests.rust.lines": measured("tests.rust.lines", 91.2, head="old")}
        on_dev = judge(
            engine, "thresholds:\n  tests.rust.lines: 50\n", stale, "dev", head="new"
        )
        on_prod = judge(
            engine, "thresholds:\n  tests.rust.lines: 50\n", stale, "prod", head="new"
        )
        assert on_dev.failures and not on_dev.refuses
        assert on_prod.refuses


