def rewrite(text, block):
    """``text`` with everything between the markers replaced by ``block``.

    The markers are found in ``block`` itself rather than passed separately, so a block can only
    ever be written into a file marked for that same format. Idempotent by construction: what is
    written between the markers includes them, and what is replaced is everything from one to the
    other.
    """
    begin, end = next(
        (pair for pair in MARKERS.values() if block.startswith(pair[0])), (None, None)
    )
    if begin is None:
        raise ValueError("the block carries no markers")

    start = text.find(begin)
    stop = text.find(end, start + len(begin)) if start != -1 else -1
    if start == -1 or stop == -1:
        raise MarkersMissing(
            f"the file carries no {begin} … {end} pair. "
            "Paste both lines where the table should go, and run this again."
        )
    return text[:start] + block.rstrip("\n") + text[stop + len(end) :]


RENDERERS = {
    "json": render_json,
    "html": render_html,
    "markdown": render_markdown,
    "rst": render_rst,
}


def render(model, style, table=DEFAULT_TABLE):
    """One rendering of the model, as text. ``badges`` is not here: it is several files.

    ``--table`` chooses among the three arrangements, and only the two text formats have it.
    ``json`` is the model and a table of it would be a second, lossy one; ``html`` already carries
    all three as tabs, so asking it for one would be asking for a page with two tabs removed. Both
    refuse rather than ignore the argument — silently rendering something other than what was asked
    for is how a hook writes the wrong file for a year.
    """
    if style not in RENDERERS:
        raise KeyError(f"{style} is no rendering; the formats are {', '.join(FORMATS)}")
    if table not in TABLES:
        raise KeyError(f"{table} is no table; the tables are {', '.join(TABLES)}")
    if style not in MARKERS:
        if table != DEFAULT_TABLE:
            raise KeyError(
                f"{style} has no tables; --table is for {', '.join(MARKERS)}"
            )
        return RENDERERS[style](model)
    return RENDERERS[style](model, table)
