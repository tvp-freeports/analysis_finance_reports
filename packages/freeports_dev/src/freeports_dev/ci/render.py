class MarkersMissing(Exception):
    """A file to be rewritten does not say where the report goes.

    Deliberately not "append it at the end". Where a table belongs in a README is a judgement about
    that README, and a command that guessed would put one under a licence notice once and then keep
    it there for ever.
    """


