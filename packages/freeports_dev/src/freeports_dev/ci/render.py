def _rst_cell(table, index, cell):
    return f"``{cell}``" if index in _CODED[table] and cell != "—" else str(cell)


def _rst_table(headers, rows):
    """A simple table: the rules are as wide as the widest cell in each column."""
    widths = [
        max(len(header), *(len(row[index]) for row in rows))
        for index, header in enumerate(headers)
    ]
    rule = "  ".join("=" * width for width in widths)

    def line(cells):
        return "  ".join(
            cell.ljust(width) for cell, width in zip(cells, widths)
        ).rstrip()

    return [rule, line(headers), rule, *(line(row) for row in rows), rule, ""]


def render_rst(model, table=DEFAULT_TABLE):
    spec = TABLES[table]
    rows = [
        tuple(_rst_cell(table, index, cell) for index, cell in enumerate(row))
        for row in ROWS[table](model)
    ] or [("—",) * len(spec.headers)]

    begin, end = MARKERS["rst"]
    lines = [begin, f".. {WRITTEN_BY}", ""]
    if table != DEFAULT_TABLE:
        lines.extend([f"**{spec.heading}**", "", spec.prose, ""])
    lines.extend(
        [
            summary(model),
            "",
            f"*{NOTICE}*",
            f"`{NOTICE_LINK_TEXT} <{GATE_DOC_URL}>`_.",
            "",
        ]
    )
    lines.extend(_rst_table(spec.headers, rows))
    for line in _tail_lines(model, table):
        lines.extend([line, ""])
    for state in _legend_states(model) if table == DEFAULT_TABLE else []:
        lines.extend([f"*{VERDICT_LABEL[state]}*", f"   {VERDICT_LEGEND[state]}", ""])
    lines.extend([end, ""])
    return "\n".join(lines)


