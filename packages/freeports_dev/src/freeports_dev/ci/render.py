def _summary_rows(model):
    for entry in model["metrics"]:
        yield (
            entry["metric"],
            _figure(entry),
            _figure(entry, "minimum"),
            VERDICT_LABEL[entry["verdict"]],
        )


def _threshold_rows(model):
    """Only the gated metrics, because a minimum is what this table is about.

    A metric nobody set a minimum for is in the summary, where it is visible and says "not gated" —
    which is how a threshold eventually gets seeded at a figure somebody has actually seen.
    """
    for entry in model["metrics"]:
        if entry["minimum"] is None:
            continue
        yield (
            entry["metric"],
            _figure(entry, "minimum"),
            _figure(entry),
            entry["cost"] or "—",
            entry["description"] or "—",
        )


#: How many members of a list-valued breakdown a line spells out before it stops counting them.
#: A format with two hundred tested pages has said everything it has to say by the tenth.
_LIST_SHOWN = 8


def _breakdown_value(entry, value):
    """One line of a breakdown, formatted by what that breakdown actually holds.

    The measurements do not all break down into the same kind of thing, and pretending they do is
    how a renderer crashes on a repository it was not written against. Four shapes occur today:

    ==============================  ===========================  ====================
    metric                          a value is                   read as
    ==============================  ===========================  ====================
    ``docs.*``, ``tests.*.lines``   a percentage                 ``72.9 %``
    ``lint.*``                      a count of findings          ``4``
    ``tests.formats.integration``   whether a test exists        ``yes`` / ``no``
    ``tests.formats.single_page``   which pages carry a fixture  ``2 pages: 13, 14``
    ==============================  ===========================  ====================

    Anything else is printed as it stands rather than guessed at. A breakdown is written by the
    command that measured it, and a renderer that insisted on a shape would be the thing standing
    between a new metric and being visible at all.
    """
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        shown = ", ".join(str(item) for item in value[:_LIST_SHOWN])
        more = (
            "" if len(value) <= _LIST_SHOWN else f", +{len(value) - _LIST_SHOWN} more"
        )
        return (
            f"{_plural(len(value), 'page', 'pages')}: {shown}{more}"
            if value
            else "none"
        )
    if isinstance(value, (int, float)):
        if entry.get("unit") == "percent":
            return f"{value:.1f} %"
        if isinstance(value, float) and value.is_integer():
            return str(int(value))
        return f"{value:g}"
    return str(value)


def _goodness(entry, value):
    """How well one breakdown line is doing, on whatever scale that line is on.

    One number so that every breakdown can be sorted worst first by the same rule, and signed so
    that "worst" is always the low end -- a count of lint findings is the one quantity here where a
    bigger number is a worse repository, and negating it is cheaper than a second sort order that
    somebody would eventually apply to the wrong metric.
    """
    if isinstance(value, bool):
        return 0 if not value else 1
    if isinstance(value, (list, tuple)):
        return len(value)
    if isinstance(value, (int, float)):
        return -value if entry.get("unit") == "score" else value
    return 0


def _worst_first(entry):
    """One metric's breakdown, worst first.

    Ties are broken by name, so two runs of the same repository produce the same file and a
    committed page does not churn on dictionary order.
    """
    return sorted(
        (entry.get("breakdown") or {}).items(),
        key=lambda item: (_goodness(entry, item[1]), item[0]),
    )


def _answers_for_something(value):
    """Whether a breakdown line has anything to answer for.

    A yes/no breakdown — "does this document have a whole-document test at all" — says everything
    it has to say in its *no* lines. Listing the thirty-one documents that do have one pads the page
    with rows nobody acts on and pushes the five that need attention off the top of it, and the
    proportion is already the metric's own figure. Every other shape of value stays: a file at 100 %
    is worth seeing beside one at 12 %, because there the number *is* the answer.
    """
    return not (isinstance(value, bool) and value)


def _document_lines(entry):
    """The breakdown lines of one metric that a document would show, worst first."""
    return [item for item in _worst_first(entry) if _answers_for_something(item[1])]


def _breakdown_rows(model):
    """The breakdown lines a *document* carries, which is not all of them.

    The crate alone breaks down into a hundred and twenty files, and a page listing every one of
    them changes in every commit that moves any of them — a committed file whose diff nobody can
    read is a committed file nobody reads. So a document shows the worst few per metric, which is
    the end somebody would act on, and says how many it left out. The model keeps all of them:
    ``--format json`` is the complete answer, and it is the one that does not go in a commit.
    """
    limit = model.get("breakdown_limit") or 0
    for entry in model["metrics"]:
        items = _document_lines(entry)
        for item, value in items[:limit] if limit else items:
            yield entry["metric"], item, _breakdown_value(entry, value)


def breakdown_omitted(model):
    """How many breakdown lines each metric has that a document does not show."""
    limit = model.get("breakdown_limit") or 0
    if not limit:
        return []
    return [
        (entry["metric"], len(_document_lines(entry)) - limit)
        for entry in model["metrics"]
        if len(_document_lines(entry)) > limit
    ]


ROWS = {
    "summary": _summary_rows,
    "thresholds": _threshold_rows,
    "breakdown": _breakdown_rows,
}


