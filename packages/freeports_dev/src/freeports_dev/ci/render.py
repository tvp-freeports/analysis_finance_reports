def _cost_of(name):
    metric = metrics.find(name)
    return metric.cost if metric is not None else None


def _description_of(name):
    metric = metrics.find(name)
    return metric.description if metric is not None else None


def _within(root, item):
    """A breakdown key with the machine taken out of it.

    ``cargo llvm-cov`` reports absolute paths, so a breakdown taken here reads
    ``/home/somebody/work/analysis_finance_reports/packages/…`` — which names the person's home
    directory in a file the repository commits, and makes the same repository render differently on
    every machine that renders it. The key is a path *inside this repository* or it is not a path at
    all, and either way what belongs in the document is the part that is about the code.
    """
    if root is None or not isinstance(item, str):
        return item
    try:
        return str(Path(item).resolve().relative_to(Path(root).resolve()))
    except (ValueError, OSError):
        return item


def status_of(verdicts, conditions=(), skipped_slow=()):
    """The one word a badge carries, in the order the three cases have to be decided.

    ``failing`` first: a figure known to be under its minimum is the strongest thing this run can
    say, and one unmeasured metric beside it does not soften that. ``inconclusive`` second, and it
    covers the skipped figures too — a metric a ``--skip-slow`` run never looked at must not be
    mistaken afterwards for one that passed.

    **A run that gated nothing is inconclusive, not passing.** "Passing" means every gated figure
    cleared its minimum, and with no minima there is nothing that cleared anything — a green badge
    on a repository nobody has configured is the vacuous truth this whole mechanism exists to keep
    out of a README. It is also the first state of every repository `init-format-repo` creates, and
    it says so.
    """
    if any(v.state == ci_gate.BELOW for v in verdicts) or any(
        c.fails for c in conditions
    ):
        return FAILING
    if (
        any(v.state in (ci_gate.UNMEASURED, ci_gate.STALE) for v in verdicts)
        or skipped_slow
    ):
        return INCONCLUSIVE
    if not any(v.minimum is not None for v in verdicts):
        return INCONCLUSIVE
    return PASSING


def build(gate, config=None, name=None):
    """The model of one gate run: every metric, every condition, and what they add up to.

    It carries what the gate decided *and* what the registry knows about each metric — its cost
    class and the sentence saying what it measures. A table reading ``docs.rust 39.4 %`` and nothing
    else tells a reader a number and not what was counted, and the reader of a documentation page
    has no ``--help`` to hand.
    """
    branch_class = gate.branch_class
    root = config.root if config is not None else None
    entries = []
    for verdict in gate.verdicts:
        measurement = verdict.measurement
        entries.append(
            {
                "metric": verdict.metric,
                "value": verdict.value,
                "unit": verdict.unit,
                "minimum": verdict.minimum,
                "verdict": verdict.state,
                "reason": verdict.reason,
                "cost": _cost_of(verdict.metric),
                "description": _description_of(verdict.metric),
                "head": measurement.head if measurement is not None else None,
                "breakdown": (
                    {_within(root, k): v for k, v in measurement.breakdown.items()}
                    if measurement is not None
                    else {}
                ),
                "detail": dict(measurement.detail) if measurement is not None else {},
            }
        )

    counts = {key: 0 for key in TOTAL_KEY.values()}
    for entry in entries:
        counts[TOTAL_KEY[entry["verdict"]]] += 1

    return {
        "repository": {
            "name": name or (config.root.name if config is not None else None),
            "kind": config.repo_kind if config is not None else None,
        },
        "branch": {
            "name": branch_class.branch,
            "class": branch_class.name,
            "reason": branch_class.reason,
            "enforced": branch_class.refuses,
        },
        "status": status_of(gate.verdicts, gate.conditions, gate.skipped_slow),
        "breakdown_limit": (
            config.breakdown_limit if config is not None else DEFAULT_BREAKDOWN_LIMIT
        ),
        "refused": gate.refuses,
        "totals": {
            "metrics": len(entries),
            "gated": sum(1 for e in entries if e["minimum"] is not None),
            **counts,
        },
        "metrics": entries,
        "conditions": [
            {
                "name": condition.name,
                "ok": condition.ok,
                "applicable": condition.applicable,
                "detail": condition.detail,
            }
            for condition in gate.conditions
        ],
        "skipped_slow": sorted(gate.skipped_slow),
    }


