#: Verdana at 11px, which is what shields measures against. An approximation is good enough here:
#: the consequence of being a pixel out is a badge with slightly wide padding, and the alternative
#: is shipping a font metrics table for a dozen short strings.
_CHARACTER_WIDTH = 7.0
_SIDE_PADDING = 10.0


def _badge_svg(label, message, color):
    """One shields-style badge, drawn here rather than fetched.

    Drawn locally so that generating a report needs no network: a command that fetched its own
    badges would fail in exactly the places this whole pipeline exists to keep working.
    """
    label_width = _CHARACTER_WIDTH * len(label) + _SIDE_PADDING * 2
    message_width = _CHARACTER_WIDTH * len(message) + _SIDE_PADDING * 2
    total = label_width + message_width
    label_middle = label_width / 2
    message_middle = label_width + message_width / 2
    fill = COLORS.get(color, COLORS["grey"])
    title = html.escape(f"{label}: {message}")
    label = html.escape(label)
    message = html.escape(message)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" \
width="{total:.0f}" height="20" role="img" aria-label="{title}">
<title>{title}</title>
<linearGradient id="gradient" x2="0" y2="100%">
<stop offset="0" stop-color="#bbb" stop-opacity=".1"/>
<stop offset="1" stop-opacity=".1"/>
</linearGradient>
<clipPath id="rounded"><rect width="{total:.0f}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#rounded)">
<rect width="{label_width:.0f}" height="20" fill="#555"/>
<rect x="{label_width:.0f}" width="{message_width:.0f}" height="20" fill="{fill}"/>
<rect width="{total:.0f}" height="20" fill="url(#gradient)"/>
</g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,DejaVu Sans,sans-serif" font-size="11">
<text x="{label_middle:.0f}" y="15" fill="#010101" fill-opacity=".3">{label}</text>
<text x="{label_middle:.0f}" y="14">{label}</text>
<text x="{message_middle:.0f}" y="15" fill="#010101" fill-opacity=".3">{message}</text>
<text x="{message_middle:.0f}" y="14">{message}</text>
</g>
</svg>
"""


def _endpoint(label, message, color):
    """The same badge as data, for anyone who would rather shields.io drew it."""
    return (
        json.dumps(
            {"schemaVersion": 1, "label": label, "message": message, "color": color},
            indent=2,
        )
        + "\n"
    )


def _scale_color(percentage):
    """The colour of a figure on its own terms, from a percentage."""
    if percentage is None:
        return "grey"
    for threshold, color in (
        (90, "brightgreen"),
        (75, "green"),
        (50, "yellow"),
        (25, "orange"),
    ):
        if percentage >= threshold:
            return color
    return "red"


def metric_badge(entry):
    """One metric as a badge: what it reads, and what colour that is worth.

    **The colour is the figure, not the verdict** — with two exceptions. A figure under this
    repository's own minimum is red whatever its value, because falling short of a rule the
    repository wrote down is news; and one nobody could compute, or one taken at another commit, is
    grey, because it is not a figure about this code at all.

    Everywhere else the colour is the absolute number. Painting 32 % green on the grounds that 32 is
    what this repository currently demands would flatter a reader with the project's own floor, and
    a badge exists to be read by somebody who has not opened `ci.yaml`.
    """
    label = entry["metric"]
    if entry["verdict"] == ci_gate.UNMEASURED:
        return label, "not measured", "grey"
    if entry["verdict"] == ci_gate.STALE:
        return label, "stale", "grey"
    if entry["value"] is None:
        return label, "n/a", "grey"
    message = _figure(entry).replace(" %", "%")
    if entry["verdict"] == ci_gate.BELOW:
        return label, message, "red"
    scale = entry["value"] * 10 if entry["unit"] == "score" else entry["value"]
    return label, message, _scale_color(scale)


def badge_name(metric):
    """The file a metric's badge is written to: the dotted name with dots as dashes.

    The same mechanical rule :func:`freeports_dev.ci.report.file_name` uses for the measurement
    files, so a person who knows the metric can find both without a lookup table.
    """
    return metric.replace(".", "-")


def render_badges(model):
    """The badges, as a mapping of filename to content.

    One for the run as a whole, and one for every metric that has something to say — measured, or
    gated, or both. A metric that is neither is left out: a wall of ``n/a`` badges in a README says
    nothing about the repository and hides the ones that do.
    """
    answer = {}
    status = model["status"]
    for name, (label, message, color) in {
        "ci-status": ("ci", status, STATUS_COLORS.get(status, "grey")),
        **{
            badge_name(entry["metric"]): metric_badge(entry)
            for entry in model["metrics"]
            if entry["value"] is not None or entry["minimum"] is not None
        },
    }.items():
        answer[f"{name}.svg"] = _badge_svg(label, message, color)
        answer[f"{name}.json"] = _endpoint(label, message, color)
    return answer


