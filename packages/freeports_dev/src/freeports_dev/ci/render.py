"""``freeports-dev ci-report``: what a gate run looks like once it is written down.

The measurement commands establish facts and write them into ``reports/``; :mod:`freeports_dev.ci.gate`
judges them; this renders the judgement, and does nothing else. That is the same three-way split
``freeports-validate`` follows — ``collect``, ``report``, ``check-grants`` — and it is here for the
same reason: a rendering that measured something of its own would be a second source of truth for a
figure the gate already decided about.

Every rendering is a pure function of the model, which is why the model exists at all::

    $ freeports-dev ci-report --format json | jq '.metrics[] | select(.verdict != "pass")'
    $ freeports-dev ci-report --format html     --out docs/source/_extra/ci/report.html
    $ freeports-dev ci-report --format badges   --out ci/report/badges/
    $ freeports-dev ci-report --format markdown --out README.md
    $ freeports-dev ci-report --format rst --table breakdown --out docs/source/dev/ci-report/breakdown.rst

The first of those answers questions no rendering here anticipated, and it stays available however
the others change.

**This command never refuses anything.** ``ci-check`` decides whether a commit is made; this says
what the run found, and exits non-zero only when it could not write what it was asked to write. A
hook that could be stopped by its own report would be a hook people remove.

**Nothing here carries a timestamp, and no rendering names a commit unless a figure is stale.**
These artefacts are committed — badges in a ``README.md``, tables in a documentation tree — and a
date, or the head recorded beside every figure, would put a diff in every commit saying nothing had
changed. The commit is named in exactly the place where it is the news: beside a figure that was
measured at another one.
"""

