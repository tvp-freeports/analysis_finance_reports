def _figure(entry, key="value"):
    """A figure at the precision its unit is judged at, or the dash that means there is none.

    A lint score is a ratchet held just under ten, so it is printed at three decimals: two would
    round 9.998 to ``10.00`` beside a minimum of 10, which reads as a bug in the tool rather than a
    figure in the code.
    """
    value = entry.get(key)
    if value is None:
        return "—"
    if entry.get("unit") == "score":
        return f"{value:.3f}"
    if entry.get("unit") == "percent":
        return f"{value:.1f} %"
    return f"{value:g}"


def _plural(count, singular, plural):
    """``1 metric`` / ``2 metrics``, written out rather than parenthesised.

    ``metric(s)`` costs nothing to produce and makes every sentence slightly harder to read than it
    needs to be, in a document whose whole purpose is to be read.
    """
    return f"{count} {singular if count == 1 else plural}"


def _tally(model):
    """The non-zero verdict counts, in the order the gate explains them.

    Zeroes are left out. "0 stale" in a summary line is a sentence about nothing, and four of them
    push the one number that matters off the end of the line.
    """
    totals = model["totals"]
    parts = []
    for state, word in (
        (ci_gate.PASS, "pass"),
        (ci_gate.BELOW, "below the minimum"),
        (ci_gate.UNMEASURED, "not measured"),
        (ci_gate.STALE, "measured at another commit"),
    ):
        count = totals.get(TOTAL_KEY[state])
        if count:
            parts.append(f"{count} {word}")
    return parts or ["nothing gated yet"]


def _enforcement(model):
    return (
        "thresholds are enforced"
        if model["branch"]["enforced"]
        else "thresholds are reported, not enforced"
    )


def _where(model):
    branch = model["branch"]
    return f"branch {branch['name']}" if branch["name"] else "no branch checked out"


def summary(model):
    """The one sentence every rendering opens with."""
    totals = model["totals"]
    return (
        f"{_plural(totals['metrics'], 'metric', 'metrics')}, {totals['gated']} gated: "
        f"{', '.join(_tally(model))}; "
        f"{_where(model)} → {model['branch']['class']} ({_enforcement(model)}); "
        f"ci-check: {model['status']}"
    )


def failing_conditions(model):
    """The conditions that did not hold — a suite that failed, a rule that was broken.

    They are not metrics: they have no unit, no minimum and nothing to plot, so every rendering
    prints them as sentences under the table rather than inventing table cells for them.
    """
    return [c for c in model["conditions"] if c["applicable"] and not c["ok"]]


def explained(model):
    """Every metric that did not pass and has something to say about why.

    The sentences are the part that matters. A table of verdicts tells somebody a figure is wrong;
    a sentence naming the tool, the number and the command tells them what to do about it.
    """
    return [
        entry
        for entry in model["metrics"]
        if entry["verdict"] in (ci_gate.BELOW, ci_gate.UNMEASURED, ci_gate.STALE)
        and entry["reason"]
    ]


def _by_reason(model):
    """The failures, one sentence per *reason* rather than one per metric.

    A repository whose last full run was two commits ago has the same staleness sentence twelve
    times over, and twelve copies of one fact push everything else off the page. Metrics sharing a
    reason share a line, in the order the table lists them; two metrics whose reasons differ by so
    much as the note about a per-package minimum still get their own, because at that point the
    sentences are no longer the same fact.
    """
    grouped = {}
    for entry in explained(model):
        grouped.setdefault(entry["reason"], []).append(entry["metric"])
    return list(grouped.items())


def _legend_states(model):
    """The verdicts actually on the table, so the legend explains those and no others.

    A page gains nothing from the explanation of a word it does not contain, and the next reader
    would have to check whether it was stale.
    """
    seen = []
    for entry in model["metrics"]:
        if entry["verdict"] not in seen:
            seen.append(entry["verdict"])
    return [state for state in VERDICT_LABEL if state in seen]


