#: The columns whose cells are set as literals, per table. A metric name, a path and a lint rule are
#: all code; a sentence describing what a metric measures is not.
_CODED = {"summary": {0}, "thresholds": {0}, "breakdown": {0, 1}}


def _md_cell(table, index, cell):
    return f"`{cell}`" if index in _CODED[table] and cell != "—" else str(cell)


def _tail_lines(model, table):
    """What goes under every table: why a figure fell short, and what did not hold.

    Only under ``summary``. The other two tables answer a question that has nothing to do with a
    verdict — what is demanded, and where a number comes from — and repeating the failures under
    each of them would make three copies of one list to keep in step.
    """
    if table == "breakdown":
        omitted = breakdown_omitted(model)
        if not omitted:
            return []
        listed = ", ".join(f"{metric} ({count} more)" for metric, count in omitted)
        return [
            f"Only the worst {model['breakdown_limit']} lines of each metric are shown: {listed}. "
            "`freeports-dev ci-report --format json` carries every one of them."
        ]
    if table != "summary":
        return []
    lines = []
    for reason, named in _by_reason(model):
        lines.append(f"{', '.join(named)} — {reason}")
    for condition in failing_conditions(model):
        lines.append(f"{condition['name']} — {condition['detail']}")
    if model["skipped_slow"]:
        lines.append(
            "Skipped, because --skip-slow was given: "
            + ", ".join(model["skipped_slow"])
            + ". Those figures were not checked at all."
        )
    return lines


def render_markdown(model, table=DEFAULT_TABLE):
    spec = TABLES[table]
    rows = list(ROWS[table](model))
    begin, end = MARKERS["markdown"]
    lines = [begin, f"<!-- {WRITTEN_BY} -->", ""]
    if table != DEFAULT_TABLE:
        lines.extend([f"### {spec.heading}", "", spec.prose, ""])
    lines.extend(
        [
            summary(model),
            "",
            f"*{NOTICE}* [{NOTICE_LINK_TEXT}]({GATE_DOC_URL}).",
            "",
            "| " + " | ".join(spec.headers) + " |",
            "| " + " | ".join(spec.alignment) + " |",
        ]
    )
    if rows:
        for row in rows:
            lines.append(
                "| "
                + " | ".join(_md_cell(table, i, c) for i, c in enumerate(row))
                + " |"
            )
    else:
        lines.append("| " + " | ".join("—" for _ in spec.headers) + " |")
    for line in _tail_lines(model, table):
        lines.extend(["", line])
    for state in _legend_states(model) if table == DEFAULT_TABLE else []:
        lines.extend(["", f"*{VERDICT_LABEL[state]}* — {VERDICT_LEGEND[state]}"])
    lines.extend(["", end, ""])
    return "\n".join(lines)


