# reStructuredText
# ---------------------------------------------------------------------------


def _rst_cell(model, dimension, value, mark=""):
    """No link here, deliberately.

    A methodology's URI would have to be an inline target, and a simple table whose cells carry
    inline targets is unreadable as text -- which is the only reason anyone writes reStructuredText
    by hand. The URIs are listed under the table instead, once each.
    """
    if dimension == "file":
        return f"``{value}``{mark}"
    return f"{value}{mark}"


def _rst_summary_rows(model):
    for methodology in model["methodologies"]:
        yield (
            methodology["name"],
            str(methodology["grants"]),
            _coverage_text(methodology["coverage"]),
            ", ".join(sorted({a["contributor"] for a in methodology["adoptions"]})),
        )


def _rst_pair_rows(model, table):
    for group, listed, states, mark in _pairs(model, table):
        yield (
            _rst_cell(model, table.group, group),
            _rst_cell(model, table.listed, listed, mark),
            states,
        )


def _rst_table(headers, rows):
    """A simple table: the rules are as wide as the widest cell in each column."""
    widths = [
        max(len(header), *(len(row[index]) for row in rows))
        for index, header in enumerate(headers)
    ]
    rule = "  ".join("=" * width for width in widths)

    def line(cells):
        return "  ".join(
            cell.ljust(width) for cell, width in zip(cells, widths)
        ).rstrip()

    return [rule, line(headers), rule, *(line(row) for row in rows), rule, ""]


def render_rst(model, table=DEFAULT_TABLE):
    spec = TABLES[table]
    if table == DEFAULT_TABLE:
        rows = list(_rst_summary_rows(model))
    else:
        rows = list(_rst_pair_rows(model, spec))
    rows = rows or [("—",) * len(spec.headers)]

    begin, end = MARKERS["rst"]
    lines = [begin, f".. {WRITTEN_BY}", ""]
    if spec.mirrors:
        lines.extend(
            [
                f"**{spec.heading}**",
                "",
                f"The same view as ``freeports-validate {spec.mirrors}``, "
                "for the whole repository at once.",
                "",
            ]
        )
    lines.extend(
        [
            _summary(model),
            "",
            f"*{NOTICE}*",
            f"`{NOTICE_LINK_TEXT} <{GENERAL_METHODOLOGY_URL}>`_.",
            "",
        ]
    )
    lines.extend(_rst_table(spec.headers, rows))
    for legend in _legends(model, spec) if spec.mirrors else []:
        lines.extend([legend, ""])

    # The methodologies and where each resolved from, under every table rather than only under the
    # summary: a reader looking at a name in any of the six is asking the same question about it.
    for methodology in model["methodologies"]:
        if methodology["uri"]:
            lines.append(f"* {methodology['name']}: {methodology['uri']}")
    lines.extend(["", end, ""])
    return "\n".join(lines)


def rewrite(text, block):
    """``text`` with everything between the markers replaced by ``block``.

    The markers are found in ``block`` itself rather than passed separately, so a block can only
    ever be written into a file marked for that same format. Idempotent by construction: what is
    written between the markers includes them, and what is replaced is everything from one to the
    other.
    """
    begin, end = next(
        (pair for pair in MARKERS.values() if block.startswith(pair[0])), (None, None)
    )
    if begin is None:
        raise ValueError("the block carries no markers")

    start = text.find(begin)
    stop = text.find(end, start + len(begin)) if start != -1 else -1
    if start == -1 or stop == -1:
        raise MarkersMissing(
            f"the file carries no {begin} … {end} pair. "
            "Paste both lines where the table should go, and run this again."
        )
    return text[:start] + block.rstrip("\n") + text[stop + len(end) :]


