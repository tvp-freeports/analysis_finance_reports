#!/usr/bin/env python3
"""Turning the collected model into something a person or a README can read.

`bin/collect` establishes the facts -- it walks the validation documents, resolves each methodology
from the configured sources, hashes what it finds and compares. This renders them, and does nothing
else. That is the split the whole command follows: **bash establishes facts, Python parses and
renders**, so everything that decides something about trust stays a shell command a user can retype.

Every rendering here is a pure function of the model, which is why the model exists at all::

    $ freeports-validate report --format json | jq '.grants[] | select(.state != "current")'
    $ freeports-validate report --format html     --out coverage.html
    $ freeports-validate report --format badges   --out docs/badges/
    $ freeports-validate report --format markdown --out README.md
    $ freeports-validate report --format markdown --table methodology-file --out covered.md

The first of those answers questions no rendering here anticipated, and it stays available however
the others change. Run by hand, this script reads the model on standard input::

    $ freeports-validate collect | python3 report.py html --out coverage.html

The three viewpoints of the HTML page are the command's three lookup subcommands -- `who-grants`
(by file), `granted-by` (by contributor), `granted-with` (by methodology). A reader who has learned
one has learned the page, and a page that invented a fourth arrangement would be teaching a second
vocabulary for the same repository.

The two text formats take the same three viewpoints one at a time, through `--table`, and in both
of each one's groupings -- six arrangements plus the summary, listed in `TABLES`. A page cannot
carry tabs, so where the HTML shows three panels a repository keeps six files, one per arrangement,
each saying in its heading which invocation it is the written-down form of.

**Nothing here carries a timestamp.** A report is a function of the repository, and a date stamped
into it would make the Markdown rewriting differ from itself on every run -- a diff in every commit
saying nothing had changed. What a reader wants to know is what the repository says now, which is
what running the command again tells them.
"""

