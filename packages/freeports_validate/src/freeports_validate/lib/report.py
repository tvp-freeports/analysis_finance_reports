def _md_cell(model, dimension, value, mark=""):
    if dimension == "file":
        return f"`{value}`{mark}"
    if dimension == "methodology":
        uri = _uri_of(model, value)
        return f"[{value}]({uri}){mark}" if uri else f"{value}{mark}"
    return f"{value}{mark}"


def _md_summary_rows(model):
    for methodology in model["methodologies"]:
        yield (
            _md_cell(model, "methodology", methodology["name"]),
            str(methodology["grants"]),
            _coverage_text(methodology["coverage"]),
            ", ".join(sorted({a["contributor"] for a in methodology["adoptions"]})),
        )


def _md_pair_rows(model, table):
    for group, listed, states, mark in _pairs(model, table):
        yield (
            _md_cell(model, table.group, group),
            _md_cell(model, table.listed, listed, mark),
            states,
        )


#: How the summary's four columns are aligned. The two numeric ones are set right, which is the one
#: thing a Markdown table can do to make figures comparable down a column.
SUMMARY_ALIGNMENT = ("---", "---:", "---:", "---")


def render_markdown(model, table=DEFAULT_TABLE):
    spec = TABLES[table]
    if table == DEFAULT_TABLE:
        rows = list(_md_summary_rows(model))
        alignment = SUMMARY_ALIGNMENT
        empty = ("—",) * len(spec.headers)
    else:
        rows = list(_md_pair_rows(model, spec))
        alignment = ("---",) * len(spec.headers)
        empty = ("—",) * len(spec.headers)

    begin, end = MARKERS["markdown"]
    lines = [begin, f"<!-- {WRITTEN_BY} -->", ""]
    if spec.mirrors:
        lines.extend(
            [
                f"### {spec.heading}",
                "",
                f"The same view as `freeports-validate {spec.mirrors}`, "
                "for the whole repository at once.",
                "",
            ]
        )
    lines.extend(
        [
            _summary(model),
            "",
            f"*{NOTICE}* [{NOTICE_LINK_TEXT}]({GENERAL_METHODOLOGY_URL}).",
            "",
            "| " + " | ".join(spec.headers) + " |",
            "| " + " | ".join(alignment) + " |",
        ]
    )
    lines.extend("| " + " | ".join(row) + " |" for row in rows or [empty])
    for legend in _legends(model, spec) if spec.mirrors else []:
        lines.extend(["", legend])
    lines.extend(["", end, ""])
    return "\n".join(lines)


