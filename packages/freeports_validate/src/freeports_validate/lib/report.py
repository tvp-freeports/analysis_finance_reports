WRITTEN_BY = (
    "Written by `freeports-validate report`. Anything between the markers is replaced."
)


class Table:
    """One arrangement of the same repository: what it groups by, and what it lists.

    The repository has three dimensions -- file, contributor, methodology -- and a lookup is a
    choice of two of them: group by the first, list the second. Taken in every order that is six
    tables, which is exactly what the three lookup subcommands are with and without their flag. The
    name of each reads as *grouped by the first, listing the second*; `mirrors` says which
    invocation it is the written-down form of, so nobody has to learn a second vocabulary for a
    repository they can already ask about on the command line.

    `group` and `listed` are keys of a grant in the model, not display words: the whole table is
    built by reading those two fields off every grant, which is why adding a seventh arrangement
    would be a line of data rather than a function.
    """

    #: Which key of a grant each dimension is, and how a value of it is written in a table cell.
    #: A path is code and is set in a literal; a methodology is a document and is linked to the text
    #: it resolved from; a person is a name and is left alone.
    DIMENSIONS = {
        "file": "path",
        "contributor": "contributor",
        "methodology": "methodology",
    }

    def __init__(self, group, listed, heading, mirrors, headers):
        self.group = group
        self.listed = listed
        self.heading = heading
        self.mirrors = mirrors
        self.headers = headers


#: The seven values of `--table`. `summary` is first because it is the default and the one the
#: renderings have always had; the six after it are in the order the three lookup subcommands come
#: in, each immediately followed by its flag.
