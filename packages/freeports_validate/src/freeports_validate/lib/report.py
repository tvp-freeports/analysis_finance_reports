#: Verdana at 11px, which is what shields measures against. An approximation is good enough here:
#: the consequence of being a pixel out is a badge with slightly wide padding, and the alternative
#: is shipping a font metrics table for three short strings.
_CHARACTER_WIDTH = 7.0
_SIDE_PADDING = 10.0


def _badge_svg(label, message, color):
    """One shields-style badge, drawn here rather than fetched.

    Drawn locally so that generating a report needs no network either: a command that fetched its
    own badges would make `--format badges` fail in the same places `--offline` exists for.
    """
    label_width = _CHARACTER_WIDTH * len(label) + _SIDE_PADDING * 2
    message_width = _CHARACTER_WIDTH * len(message) + _SIDE_PADDING * 2
    total = label_width + message_width
    label_middle = label_width / 2
    message_middle = label_width + message_width / 2
    fill = COLORS.get(color, COLORS["grey"])
    title = html.escape(f"{label}: {message}")
    label = html.escape(label)
    message = html.escape(message)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" \
width="{total:.0f}" height="20" role="img" aria-label="{title}">
<title>{title}</title>
<linearGradient id="gradient" x2="0" y2="100%">
<stop offset="0" stop-color="#bbb" stop-opacity=".1"/>
<stop offset="1" stop-opacity=".1"/>
</linearGradient>
<clipPath id="rounded"><rect width="{total:.0f}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#rounded)">
<rect width="{label_width:.0f}" height="20" fill="#555"/>
<rect x="{label_width:.0f}" width="{message_width:.0f}" height="20" fill="{fill}"/>
<rect width="{total:.0f}" height="20" fill="url(#gradient)"/>
</g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,DejaVu Sans,sans-serif" font-size="11">
<text x="{label_middle:.0f}" y="15" fill="#010101" fill-opacity=".3">{label}</text>
<text x="{label_middle:.0f}" y="14">{label}</text>
<text x="{message_middle:.0f}" y="15" fill="#010101" fill-opacity=".3">{message}</text>
<text x="{message_middle:.0f}" y="14">{message}</text>
</g>
</svg>
"""


def _endpoint(label, message, color):
    """The same badge as data, for anyone who would rather shields.io drew it."""
    return (
        json.dumps(
            {
                "schemaVersion": 1,
                "label": label,
                "message": message,
                "color": color,
            },
            indent=2,
        )
        + "\n"
    )


def _coverage_color(percentage):
    if percentage is None:
        return "grey"
    for threshold, color in (
        (90, "brightgreen"),
        (75, "green"),
        (50, "yellow"),
        (25, "orange"),
    ):
        if percentage >= threshold:
            return color
    return "red"


def render_badges(model):
    """The three badges, as a mapping of filename to content.

    Three because they are the three questions a README is asked: how much has been vouched for, how
    much of what could be, and does it all still hold.
    """
    percentage = _percentage(model["coverage"])
    badges = {
        "grants-total": ("grants", str(model["totals"]["grants"]), "blue"),
        "grants-coverage": (
            "coverage",
            "n/a" if percentage is None else f"{percentage}%",
            _coverage_color(percentage),
        ),
        "check-grants": (
            "check-grants",
            model["status"],
            STATUS_COLORS.get(model["status"], "grey"),
        ),
    }
    answer = {}
    for name, (label, message, color) in badges.items():
        answer[f"{name}.svg"] = _badge_svg(label, message, color)
        answer[f"{name}.json"] = _endpoint(label, message, color)
    return answer


