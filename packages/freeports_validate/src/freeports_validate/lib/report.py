#: The default, and the one every earlier caller of `render` is asking for without saying so.
DEFAULT_TABLE = "summary"


def _uri_of(model, name):
    """Where a methodology resolved from, or ``None`` when nothing could be resolved."""
    return next(
        (entry["uri"] for entry in model["methodologies"] if entry["name"] == name),
        None,
    )


def _mark_of(scopes):
    """The mark a pair of dimensions carries, given every `in_scope` its grants reported.

    A refusal outranks an unasked question. A pair holding both has been told by the methodology
    that it does not cover this, and one document failing to resolve the page afterwards does not
    unsay it.
    """
    if False in scopes:
        return " (!)"
    if None in scopes:
        return " (?)"
    return ""


def _pairs(model, table):
    """Every distinct (group, listed) pair in the grants, with its states and its mark.

    One row per pair rather than one per grant: the same file granted under the same methodology by
    two contributors' documents is one claim about that pair, and printing it twice would make a
    table disagree with the lookup subcommand it mirrors. The states of the grants behind it are
    kept -- almost always one word, and two when two documents disagree about the file, which is
    the case a reader most needs to see.
    """
    group_key = Table.DIMENSIONS[table.group]
    listed_key = Table.DIMENSIONS[table.listed]
    found = {}
    for grant in model["grants"]:
        key = (grant[group_key], grant[listed_key])
        states, scopes = found.setdefault(key, (set(), set()))
        states.add(grant["state"])
        scopes.add(grant.get("in_scope"))
    for (group, listed), (states, scopes) in sorted(found.items()):
        yield group, listed, ", ".join(sorted(states)), _mark_of(scopes)


def _legends(model, table):
    """The legend lines a table needs, and only those.

    Printed under the table and only when a mark is actually on it: a file kept under version
    control gains nothing from an explanation of a symbol it does not contain, and the next reader
    would have to check whether it was stale.
    """
    marks = {mark for _group, _listed, _states, mark in _pairs(model, table)}
    lines = []
    if " (!)" in marks:
        lines.append(OUT_OF_SCOPE_LEGEND)
    if " (?)" in marks:
        lines.append(UNRESOLVED_LEGEND)
    return lines


