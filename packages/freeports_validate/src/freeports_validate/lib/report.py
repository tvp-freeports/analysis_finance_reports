RENDERERS = {
    "json": render_json,
    "html": render_html,
    "markdown": render_markdown,
    "rst": render_rst,
}


def render(model, style, table=DEFAULT_TABLE):
    """One rendering of the model, as text. ``badges`` is not here: it is several files.

    `table` chooses among the seven arrangements of the repository, and only the two text formats
    have it. `json` is the model and a table of it would be a second, lossy one; `html` already
    carries the three viewpoints as tabs, so asking it for one of them would be asking for a page
    with two of its tabs removed. Both refuse rather than ignore the argument -- silently rendering
    something other than what was asked for is how a hook writes the wrong file for a year.
    """
    if style not in RENDERERS:
        raise KeyError(style)
    if table not in TABLES:
        raise KeyError(table)
    if style not in MARKERS:
        if table != DEFAULT_TABLE:
            raise KeyError(
                f"{style} has no tables; --table is for {', '.join(MARKERS)}"
            )
        return RENDERERS[style](model)
    return RENDERERS[style](model, table)


def _write_badges(model, directory):
    os.makedirs(directory, exist_ok=True)
    for name, content in render_badges(model).items():
        with open(os.path.join(directory, name), "w", encoding="utf-8") as handle:
            handle.write(content)


USAGE = f"Usage: report.py <{'|'.join(FORMATS)}> [--table NAME] [--out PATH]"


def main(argv):
    if not argv:
        print(USAGE, file=sys.stderr)
        return 2
    style, arguments = argv[0], argv[1:]
    if style not in FORMATS:
        print(f"Unknown format: {style}", file=sys.stderr)
        print(f"Formats: {', '.join(FORMATS)}", file=sys.stderr)
        return 2

    out = None
    table = DEFAULT_TABLE
    while arguments:
        if arguments[0] == "--out" and len(arguments) > 1:
            out = arguments[1]
            arguments = arguments[2:]
            continue
        if arguments[0] == "--table" and len(arguments) > 1:
            table = arguments[1]
            arguments = arguments[2:]
            continue
        print(f"Unexpected argument: {arguments[0]}", file=sys.stderr)
        print(USAGE, file=sys.stderr)
        return 2

    if table not in TABLES:
        print(f"Unknown table: {table}", file=sys.stderr)
        print(f"Tables: {', '.join(TABLES)}", file=sys.stderr)
        return 2

    model = json.load(sys.stdin)

    if style == "badges":
        if out is None:
            print(
                "badges are several files, so --out must name a directory to put them in",
                file=sys.stderr,
            )
            return 2
        _write_badges(model, out)
        return 0

    try:
        text = render(model, style, table)
    except KeyError as refused:
        print(refused.args[0], file=sys.stderr)
        return 2

    # Markdown and reStructuredText are rewritten *into* a file rather than over it: the table is
    # part of a README somebody wrote, and the rest of that README is theirs.
    if style in MARKERS and out is not None:
        with open(out, encoding="utf-8") as handle:
            existing = handle.read()
        try:
            updated = rewrite(existing, text)
        except MarkersMissing as missing:
            print(f"{out}: {missing}", file=sys.stderr)
            return 1
        with open(out, "w", encoding="utf-8") as handle:
            handle.write(updated)
        return 0

    if out is None:
        sys.stdout.write(text)
        return 0

    with open(out, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
